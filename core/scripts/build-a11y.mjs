// Builds the accessibility audit artifacts for the DevTools extension (all checked in, so the
// extension loads unpacked without a build step):
//   extension/vendor/a11y-audit.js     IIFE, minified, chrome116; defines window.__PERF_INTEL_A11Y__
//                                      (A11yInspect port + IBM / axe adapters + unified merge)
//   extension/vendor/a11y-rules.mjs    ESM for the panel: unified rule catalog, WCAG table, merge,
//                                      coverage views, engine source wrappers (core/inject/a11yRules.ts)
//   extension/vendor/ibm-ace.js        accessibility-checker-engine ace.js, UNCHANGED, with a header
//   extension/vendor/ibm-ace.LICENSE.txt  its ace.js.LICENSE.txt
//   extension/vendor/axe.min.js        axe-core axe.min.js, UNCHANGED (keeps its MPL-2.0 banner), with a header
//   extension/THIRD_PARTY_NOTICES.txt  copy of the repo's THIRD_PARTY_NOTICES.md ("Open-source credits")
// The panel injects a11y-audit.js and, on demand, the wrapped engines with inspectedWindow.eval.
// Upgrading an engine: bump the exact devDependency in core/package.json, update the version in
// core/a11y/loaders.ts, run `npm run build:extension` and `npm test` (the unified-coverage test lists
// source rules that need a home in core/a11y/catalog/unified.ts).
// Usage: cd core && npm run build:a11y   (also run by `npm run build:extension`)
import { build } from "esbuild";
import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const coreDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const extDir = resolve(coreDir, "..", "extension");
const vendorDir = resolve(extDir, "vendor");
const require = createRequire(resolve(coreDir, "package.json"));
const banner =
  "// GENERATED by core/scripts/build-a11y.mjs — do not edit. Regenerate: cd core && npm run build:extension\n" +
  "// Runtime accessibility audit. Rules ported from BarrierBreak eslint-plugin-a11yinspect (MIT); adapters for\n" +
  "// IBM Equal Access accessibility-checker-engine (Apache-2.0) and axe-core (MPL-2.0). See THIRD_PARTY_NOTICES.txt.";

const esbuildCommon = {
  bundle: true,
  minify: true,
  target: "chrome116",
  platform: "browser",
  legalComments: "none",
  charset: "utf8",
  banner: { js: banner },
  logLevel: "warning",
};

function pkg(name) {
  const dir = dirname(require.resolve(`${name}/package.json`));
  return { dir, version: JSON.parse(require("node:fs").readFileSync(resolve(dir, "package.json"), "utf8")).version };
}

async function checkLoaderVersions(ace, axe) {
  const src = await readFile(resolve(coreDir, "a11y/loaders.ts"), "utf8");
  const want = [
    ["IBM_ACE_VERSION", ace.version],
    ["AXE_CORE_VERSION", axe.version],
  ];
  for (const [name, v] of want) {
    if (!src.includes(`${name} = "${v}"`)) throw new Error(`core/a11y/loaders.ts ${name} does not match the installed package (${v})`);
  }
}

/** Copies the engines unchanged (header prepended) and returns their sizes. */
export async function vendorEngines() {
  const ace = pkg("accessibility-checker-engine");
  const axe = pkg("axe-core");
  await checkLoaderVersions(ace, axe);
  const aceSrc = await readFile(resolve(ace.dir, "ace.js"), "utf8");
  const aceLicense = await readFile(resolve(ace.dir, "ace.js.LICENSE.txt"), "utf8");
  const aceOut = resolve(vendorDir, "ibm-ace.js");
  await writeFile(
    aceOut,
    `// GENERATED copy of accessibility-checker-engine@${ace.version} ace.js — Apache-2.0 — do not edit.\n` +
      "// Source: https://github.com/IBMa/equal-access (accessibility-checker-engine). Copied unchanged below this header by\n" +
      "// core/scripts/build-a11y.mjs; license: vendor/ibm-ace.LICENSE.txt and THIRD_PARTY_NOTICES.txt. The panel injects it\n" +
      "// wrapped (core/a11y/loaders.ts) so it installs window.__PERF_INTEL_ACE__ and never touches window.ace.\n" +
      aceLicense.trim() +
      "\n" +
      aceSrc,
  );
  await copyFile(resolve(ace.dir, "ace.js.LICENSE.txt"), resolve(vendorDir, "ibm-ace.LICENSE.txt"));
  const axeSrc = await readFile(resolve(axe.dir, "axe.min.js"), "utf8");
  const axeOut = resolve(vendorDir, "axe.min.js");
  await writeFile(
    axeOut,
    `// GENERATED copy of axe-core@${axe.version} axe.min.js — MPL-2.0 — do not edit.\n` +
      "// Source code: https://github.com/dequelabs/axe-core (npm: axe-core). Copied unchanged below this header (its license\n" +
      "// notice follows) by core/scripts/build-a11y.mjs; see THIRD_PARTY_NOTICES.txt. The panel injects it wrapped\n" +
      "// (core/a11y/loaders.ts) so it installs window.__PERF_INTEL_AXE__ and restores any page-owned window.axe.\n" +
      axeSrc,
  );
  return { "ibm-ace.js": (await stat(aceOut)).size, "axe.min.js": (await stat(axeOut)).size };
}

/** extension/THIRD_PARTY_NOTICES.txt, opened by the panel's "Open-source credits" link. */
export async function copyNotices() {
  const out = resolve(extDir, "THIRD_PARTY_NOTICES.txt");
  const md = await readFile(resolve(coreDir, "..", "THIRD_PARTY_NOTICES.md"), "utf8");
  await writeFile(out, "GENERATED from THIRD_PARTY_NOTICES.md by core/scripts/build-a11y.mjs — do not edit.\n\n" + md);
  return (await stat(out)).size;
}

/** Builds all accessibility artifacts; returns { file: bytes }. */
export async function buildA11yBundle() {
  await mkdir(vendorDir, { recursive: true });
  const auditOut = resolve(vendorDir, "a11y-audit.js");
  await build({ ...esbuildCommon, entryPoints: [resolve(coreDir, "a11y/browser.ts")], outfile: auditOut, format: "iife" });
  const src = await readFile(auditOut, "utf8");
  if (!src.includes("__PERF_INTEL_A11Y__")) throw new Error("a11y-audit.js does not define __PERF_INTEL_A11Y__");
  const rulesOut = resolve(vendorDir, "a11y-rules.mjs");
  await build({ ...esbuildCommon, entryPoints: [resolve(coreDir, "inject/a11yRules.ts")], outfile: rulesOut, format: "esm" });
  const sizes = {
    "a11y-audit.js": (await stat(auditOut)).size,
    "a11y-rules.mjs": (await stat(rulesOut)).size,
    ...(await vendorEngines()),
  };
  sizes["THIRD_PARTY_NOTICES.txt"] = await copyNotices();
  return sizes;
}

// Run directly: node scripts/build-a11y.mjs
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const sizes = await buildA11yBundle();
  for (const [f, n] of Object.entries(sizes)) console.log(`${f.padEnd(24)} ${(n / 1024).toFixed(1)} KiB`);
}
