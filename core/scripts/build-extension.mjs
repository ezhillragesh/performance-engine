// Builds the extension's vendored core bundles (docs/PROTOCOL.md, "Build"):
//   extension/vendor/perf-engine.inject.js  IIFE, injected into the page MAIN world
//   extension/vendor/perf-analyzer.mjs      ESM, pure analyzer for the DevTools panel
//   extension/vendor/a11y-audit.js, a11y-rules.mjs, ibm-ace.js, axe.min.js, ../THIRD_PARTY_NOTICES.txt
//                                           accessibility audit + vendored engines (scripts/build-a11y.mjs)
// Output is checked in so the extension loads unpacked without a build step.
// Usage: cd core && npm run build:extension
import { build } from "esbuild";
import { mkdir, stat } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildA11yBundle } from "./build-a11y.mjs";

const coreDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = resolve(coreDir, "..", "extension", "vendor");
const banner = "// GENERATED by core/scripts/build-extension.mjs — do not edit. Regenerate: cd core && npm run build:extension";

const common = {
  bundle: true,
  minify: true,
  target: "chrome116",
  platform: "browser",
  legalComments: "none",
  banner: { js: banner },
  charset: "utf8",
  logLevel: "warning",
};

const outputs = [
  { entryPoints: [resolve(coreDir, "inject/entry.ts")], outfile: resolve(vendorDir, "perf-engine.inject.js"), format: "iife" },
  { entryPoints: [resolve(coreDir, "inject/analyzer.ts")], outfile: resolve(vendorDir, "perf-analyzer.mjs"), format: "esm" },
];

await mkdir(vendorDir, { recursive: true });
for (const options of outputs) {
  await build({ ...common, ...options });
  const { size } = await stat(options.outfile);
  console.log(`${options.outfile.slice(vendorDir.length + 1).padEnd(24)} ${(size / 1024).toFixed(1)} KiB`);
}
const a11y = await buildA11yBundle();
for (const [file, size] of Object.entries(a11y)) console.log(`${file.padEnd(24)} ${(size / 1024).toFixed(1)} KiB`);
